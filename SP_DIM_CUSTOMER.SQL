CREATE OR REPLACE PROCEDURE SP_DIM_CUSTOMER(V_INPUT VARCHAR(100))
RETURNS VARCHAR2(10000)
LANGUAGE SQL
AS
DECLARE 
V_START_TIME TIMESTAMP;
V_END_TIME TIMESTAMP;
V_SOURCE_TABLE_NAME VARCHAR2(100);
V_TARGET_TABLE_NAME VARCHAR2(100);
V_SOURCE_RECORD_COUNT NUMBER(10);
V_TARGET_RECORD_COUNT NUMBER(10);
BEGIN
LET V_STARTING_PROC := CURRENT_TIMESTAMP();
/*Step 1*/
/* GET THE START TIME */
V_START_TIME := CURRENT_TIMESTAMP();
/* Script to load the file into table */
COPY INTO PRE_STAGE_CUSTOMER
FROM @azure_export_stage/source_files/
PATTERN='.*dim_customer_.*\.txt'
FILE_FORMAT = (TYPE = CSV);
RETURN 'Files has beend loaded into table';
end;