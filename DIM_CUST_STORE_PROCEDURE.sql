CREATE OR REPLACE PROCEDURE DIM_CUSTOMER_SP(TABLE_NAME VARCHAR(100))
RETURNS VARCHAR(100)
LANGUAGE SQL
AS
DECLARE
V_START_TIME TIMESTAMP;
V_END_TIME TIMESTAMP;
V_SOURCE_TABLE_NAME VARCHAR (100);
V_TARGET_TABLE_NAME VARCHAR (100);
V_SOURCE_RECORD_COUNT NUMBER(10);
V_TARGET_RECORD_COUNT NUMBER (10);

BEGIN

LET V_STARTING_PROC := CURRENT_TIMESTAMP();

/*----------- Step 1 ---------------*/

/*GET THE START TIME */

V_START_TIME := CURRENT_TIMESTAMP();

/*----------TRUNCATE THE TABLE BEFORE INSERT THE DATE INTO TABLE-----------*/

LET Q_STAGE_DELETE := 'TRUNCATE TABLE EDW_SRC.PUBLIC.STAGE_' ||TABLE_NAME;
V_SOURCE_TABLE_NAME := 'SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.'||TABLE_NAME;
V_TARGET_TABLE_NAME := 'EDW_SRC.PUBLIC.STAGE_' ||TABLE_NAME;

SELECT COUNT(1) INTO :V_SOURCE_RECORD_COUNT FROM IDENTIFIER(:V_SOURCE_TABLE_NAME);
EXECUTE IMMEDIATE Q_STAGE_DELETE;

/* INSERT THE DATA INTO TABLE FROM THE SOURCE */

LET Q_STAGE_INSERT := 'INSERT INTO EDW_SRC.PUBLIC.STAGE_'|| TABLE_NAME||'
SELECT 
 C_CUSTKEY as CUSTKEY
,C_NAME as NAME
,C_ADDRESS as ADDRESS
,C_NATIONKEY as NATIONKEY
,C_PHONE as PHONE
,C_ACCTBAL as ACCTBAL
,C_MKTSEGMENT as MKTSEGMENT
,C_COMMENT as COMMENT from 
SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.' ||TABLE_NAME;

 EXECUTE IMMEDIATE Q_STAGE_INSERT;

 SELECT COUNT(1) INTO : V_TARGET_RECORD_COUNT FROM IDENTIFIER (:V_TARGET_TABLE_NAME);

 /* GET THE END TIME */

V_END_TIME := CURRENT_TIMESTAMP();

/* ADDING AUDIT DETAILS INTO TABLE */

INSERT INTO EDW_SRC.PUBLIC.EDW_AUDIT_LOG(SOURCE_TABLE_NAME, TARGET_TABLE_NAME, SOURCE_RECORD_COUNT, TARGET_RECORD_COUNT, START_TIME, END_TIME) VALUES
(:V_SOURCE_TABLE_NAME, :V_TARGET_TABLE_NAME, :V_SOURCE_RECORD_COUNT, :V_TARGET_RECORD_COUNT, :V_START_TIME, :V_END_TIME);


/*----------- Step 2 ---------------*/

V_START_TIME := CURRENT_TIMESTAMP();

/* DELETE THE DATA STAGE_CUSTOMER_DERIVED */

V_SOURCE_TABLE_NAME := 'EDW_SRC.PUBLIC.STAGE_' ||TABLE_NAME;

SELECT COUNT(1) INTO :V_SOURCE_RECORD_COUNT FROM IDENTIFIER (:V_SOURCE_TABLE_NAME);
LET Q_DERIVED_DELETE :='TRUNCATE TABLE EDW_SRC.PUBLIC.STAGE_' ||TABLE_NAME||'_DERIVED';

EXECUTE IMMEDIATE Q_DERIVED_DELETE;

/* LOAD THE DATA STAGE_CUSTOMER_DERIVED */

LET Q_DERIVED_INSERT := 'INSERT INTO EDW_SRC.PUBLIC.STAGE_' ||TABLE_NAME||'_DERIVED
SELECT CURRENT_TIMESTAMP() AS insert_gmt_timestamp,
            CURRENT_TIMESTAMP() AS update_gmt_timestamp,
            TO_NUMBER(TO_CHAR(CURRENT_DATE(), ''YYYYMMDD'')) AS load_date,
            TO_NUMBER(TO_CHAR(CURRENT_DATE(), ''YYYYMMDDHH24MISS'')) AS load_identifier,
            custkey,
            SPLIT_PART(name, ''#'', 2) AS customer_identifier,
            name,
            address,
            nationkey,
            phone,
            acctbal,
            mktsegment,
            comment
        FROM EDW_SRC.PUBLIC.STAGE_' || table_name;

EXECUTE IMMEDIATE Q_DERIVED_INSERT;
V_TARGET_TABLE_NAME := 'EDW_SRC.PUBLIC.STAGE_' ||TABLE_NAME||'_DERIVED';
V_END_TIME := CURRENT_TIMESTAMP();

SELECT COUNT(1) INTO :V_TARGET_RECORD_COUNT FROM IDENTIFIER (:V_TARGET_TABLE_NAME);
INSERT INTO EDW_SRC.PUBLIC.EDW_AUDIT_LOG(SOURCE_TABLE_NAME, TARGET_TABLE_NAME, SOURCE_RECORD_COUNT, TARGET_RECORD_COUNT, START_TIME, END_TIME) VALUES
(:V_SOURCE_TABLE_NAME,:V_TARGET_TABLE_NAME,:V_SOURCE_RECORD_COUNT,:V_TARGET_RECORD_COUNT,:V_START_TIME,:V_END_TIME);

/* DELETE THE DATA IN DIM CUSTOMER TABLE */

/*----------- Step 3 ---------------*/

V_START_TIME := CURRENT_TIMESTAMP();

/* DELETE THE DATA STAGE_CUSTOMER_DERIVED TABLE */

V_SOURCE_TABLE_NAME := 'EDW_SRC.PUBLIC.STAGE_' ||TABLE_NAME||'_DERIVED';

SELECT COUNT(1) INTO :V_SOURCE_RECORD_COUNT FROM IDENTIFIER (:V_SOURCE_TABLE_NAME);
LET Q_DIM_DELETE := 'DELETE FROM EDW_SRC.PUBLIC.DIM_'||TABLE_NAME||' WHERE CUSTKEY IN (SELECT DISTINCT CUSTKEY FROM EDW_SRC.PUBLIC.STAGE_' || TABLE_NAME||'_DERIVED)' ;

EXECUTE IMMEDIATE Q_DIM_DELETE;

/* INSERT THE DATA INTO DIM CUSTOMER TABLE FROM STAGE DERIVED TABLE */

LET Q_DIM_INSERT := 'INSERT INTO EDW_SRC.PUBLIC.DIM_'||TABLE_NAME||'
SELECT  CURRENT_TIMESTAMP() AS insert_gmt_timestamp,
            CURRENT_TIMESTAMP() AS update_gmt_timestamp,
            TO_NUMBER(TO_CHAR(CURRENT_DATE(), ''YYYYMMDD'')) AS load_date,
            TO_NUMBER(TO_CHAR(CURRENT_DATE(), ''YYYYMMDDHH24MISS'')) AS load_identifier,
            custkey,
            customer_identifier,
            name,
            address,
            nationkey,
            phone,
            acctbal,
            mktsegment,
            comment
        FROM EDW_SRC.PUBLIC.STAGE_' || table_name||'_DERIVED';

EXECUTE IMMEDIATE Q_DIM_INSERT;
V_TARGET_TABLE_NAME := 'EDW_SRC.PUBLIC.DIM_'||TABLE_NAME;

SELECT COUNT(1) INTO : V_SOURCE_RECORD_COUNT FROM IDENTIFIER (:V_TARGET_TABLE_NAME);

V_END_TIME := CURRENT_TIMESTAMP();

INSERT INTO EDW_SRC.PUBLIC.EDW_AUDIT_LOG(SOURCE_TABLE_NAME, TARGET_TABLE_NAME, SOURCE_RECORD_COUNT,TARGET_RECORD_COUNT,START_TIME, END_TIME) VALUES
(:V_SOURCE_TABLE_NAME, :V_TARGET_TABLE_NAME, :V_SOURCE_RECORD_COUNT, :V_TARGET_RECORD_COUNT, :V_START_TIME, :V_END_TIME);

LET V_ENDING_PROC := CURRENT_TIMESTAMP();

RETURN 'PROCEDURE SUCCESSFULLY COMPLETED' || 'START_TIME :' || V_STARTING_PROC || 'END_TIME :'|| V_ENDING_PROC;
END;


CALL DIM_CUSTOMER_SP ('CUSTOMER');

